"""Unit normalisation on real Tesseract output from data/synthetic scans."""

import pytest

from src.ingestion.common.normalize import normalize_units


@pytest.mark.parametrize(
    ("ocr", "expected"),
    [
        # RU: exponent read as digit / Cyrillic 'з', two units in one line
        ("Общая площадь здания составляет 1 402,65 м2, строительный объём — 8 496,72 мз.",
         "Общая площадь здания составляет 1 402,65 м², строительный объём — 8 496,72 м³."),
        ("Проектом принята общая площадь здания 925,14 м? при строительном объёме 5 719,61",
         "Проектом принята общая площадь здания 925,14 м² при строительном объёме 5 719,61"),
        ("Проектом принята общая площадь здания 2 553,46 м* при строительном объёме 16 608",
         "Проектом принята общая площадь здания 2 553,46 м² при строительном объёме 16 608"),
        ("Общий расход монолитного бетона составляет 714,64 мз.",
         "Общий расход монолитного бетона составляет 714,64 м³."),
        # RU table row, superscript dropped entirely: 'label | unit | value'
        ("Общая площадь здания м 1247,79", "Общая площадь здания м² 1247,79"),
        ("Ро Бтомчисле подвемной части м 1783,26", "Ро Бтомчисле подвемной части м 1783,26"),  # OCR-mangled keyword
        # KZ: keyword order differs, '?' and digit variants
        ("Жобада құрылыс көлемі 16 945,05 м3 болғанда ғимараттың жалпы ауданы 2 118,34 м? деп",
         "Жобада құрылыс көлемі 16 945,05 м³ болғанда ғимараттың жалпы ауданы 2 118,34 м² деп"),
        ("Ғимараттың жалпы ауданы 1 355,88 м?, құрылыс көлемі -- 9 112,80 м3 құрайды.",
         "Ғимараттың жалпы ауданы 1 355,88 м², құрылыс көлемі -- 9 112,80 м³ құрайды."),
        ("Монолитті бетонның жалпы шығыны 958,10 м? құрайды.",
         "Монолитті бетонның жалпы шығыны 958,10 м³ құрайды."),
        # KZ: OCR says 'м2' for masonry, which is a volume -> context wins
        ("(2 4(Керамикалық кірпіштен қалау м2 7 259,45", "(2 4(Керамикалық кірпіштен қалау м³ 7 259,45"),
        ("іргетасқа арналған В25 сыныпты бетон м2 22) 637,08", "іргетасқа арналған В25 сыныпты бетон м³ 22) 637,08"),
        ("|7 4|Керамикалық кірпіштен қалау М 178,96", "|7 4|Керамикалық кірпіштен қалау м³ 178,96"),
        # must NOT change
        ("29,9 х 17,1 м. Высота этажа — 3,6 м.", "29,9 х 17,1 м. Высота этажа — 3,6 м."),
        ("плита толщиной 900 мм из бетона класса В25", "плита толщиной 900 мм из бетона класса В25"),
        ("Іргетастар -- В25, М/6, Ғ150 сыныпты бетоннан", "Іргетастар -- В25, М/6, Ғ150 сыныпты бетоннан"),
        ("«Шымкент қаласының білім басқармасы» ММ берген", "«Шымкент қаласының білім басқармасы» ММ берген"),
        ("раствор марки М200, бетон B25", "раствор марки М200, бетон B25"),
        ("«Административное здание на 150 рабочих мест»", "«Административное здание на 150 рабочих мест»"),
    ],
)
def test_normalize_real_ocr_lines(ocr, expected):
    assert normalize_units(ocr)[0] == expected


def test_ocr_hint_used_without_keyword_and_conflicts_are_logged():
    text, fixes = normalize_units("Итого 4 500,00 м2\nкірпіштен қалау м2 259,45\nО 12 м?")
    assert text == "Итого 4 500,00 м²\nкірпіштен қалау м³ 259,45\nО 12 м?"
    assert [f.reason for f in fixes] == ["ocr_hint", "context_overrides_ocr", "unresolved"]
